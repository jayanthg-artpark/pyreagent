"""Generate pyreagent/labware/opentrons_standard.py from Opentrons labware definitions.

The ids are Opentrons load names, so the Opentrons driver can load them as-is.
Geometry (grid, well and tip volumes) comes from Opentrons' shared-data
definitions (Apache-2.0). Fetch them first:

    git clone --depth 1 --filter=blob:none --sparse https://github.com/Opentrons/opentrons.git _reference/opentrons
    git -C _reference/opentrons sparse-checkout set --no-cone "/shared-data/labware/definitions/2/*/1.json"
    python scripts/gen_opentrons_labware.py
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFINITIONS = ROOT / "_reference" / "opentrons" / "shared-data" / "labware" / "definitions" / "2"
OUT = ROOT / "pyreagent" / "labware" / "opentrons_standard.py"

LOAD_NAMES = [
    # OT-2 tips
    "opentrons_96_tiprack_10ul", "opentrons_96_tiprack_20ul", "opentrons_96_tiprack_300ul", "opentrons_96_tiprack_1000ul",
    "opentrons_96_filtertiprack_10ul", "opentrons_96_filtertiprack_20ul", "opentrons_96_filtertiprack_200ul",
    "opentrons_96_filtertiprack_1000ul",
    # Flex tips
    "opentrons_flex_96_tiprack_20ul", "opentrons_flex_96_tiprack_50ul", "opentrons_flex_96_tiprack_200ul",
    "opentrons_flex_96_tiprack_1000ul", "opentrons_flex_96_filtertiprack_50ul", "opentrons_flex_96_filtertiprack_200ul",
    "opentrons_flex_96_filtertiprack_1000ul",
    # Plates
    "corning_96_wellplate_360ul_flat", "nest_96_wellplate_200ul_flat", "nest_96_wellplate_100ul_pcr_full_skirt",
    "opentrons_96_wellplate_200ul_pcr_full_skirt", "biorad_96_wellplate_200ul_pcr", "nest_96_wellplate_2ml_deep",
    "corning_384_wellplate_112ul_flat", "biorad_384_wellplate_50ul", "corning_6_wellplate_16.8ml_flat",
    "corning_12_wellplate_6.9ml_flat", "corning_24_wellplate_3.4ml_flat", "corning_48_wellplate_1.6ml_flat",
    # Reservoirs
    "nest_12_reservoir_15ml", "nest_12_reservoir_22ml", "nest_1_reservoir_195ml", "nest_1_reservoir_290ml",
    "agilent_1_reservoir_290ml",
    # Tube racks
    "opentrons_24_tuberack_eppendorf_1.5ml_safelock_snapcap", "opentrons_24_tuberack_nest_1.5ml_snapcap",
    "opentrons_15_tuberack_falcon_15ml_conical", "opentrons_6_tuberack_falcon_50ml_conical",
]

sys.path.insert(0, str(ROOT))
from pyreagent.vendors.opentrons.labware import labware_fields  # noqa: E402


def entry(load_name: str) -> dict:
    versions = sorted((DEFINITIONS / load_name).glob("*.json"), key=lambda p: int(p.stem))
    if not versions:
        raise SystemExit(f"missing definition for {load_name} under {DEFINITIONS}")
    return labware_fields(json.loads(versions[-1].read_text(encoding="utf-8")))


def main() -> None:
    commit = subprocess.run(["git", "-C", str(DEFINITIONS), "log", "-1", "--format=%h %cs"],
                            capture_output=True, text=True).stdout.strip() or "unknown"
    items = [entry(name) for name in LOAD_NAMES]
    lines = [
        '"""Opentrons standard labware, ids = Opentrons load names.',
        "",
        "GENERATED by scripts/gen_opentrons_labware.py from Opentrons shared-data labware",
        f"definitions (Apache-2.0), Opentrons commit {commit}. Do not edit by hand.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "OPENTRONS_LABWARE: list[dict[str, object]] = [",
        *(f"    {item!r}," for item in items),
        "]",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {len(items)} labware to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
